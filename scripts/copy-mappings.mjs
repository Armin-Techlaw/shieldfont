// Post-build helper. For every JSON mapping under src/mappings it emits, into
// dist/mappings/:
//   1. <name>.json — the raw data, imported by the compiled dist/index.js via
//      JSON import attributes (the package's main entry).
//   2. <name>.js   — an ESM module that default-exports the mapping object, so
//      the `@shieldfont/core/mappings/<name>` subpath export resolves at
//      runtime (fixes ERR_MODULE_ND: the exports map pointed at a .js that was
//      never generated).
//   3. <name>.d.ts — the matching type declaration (mapping record), so the
//      same subpath resolves for TypeScript consumers.
import { mkdir, copyFile, readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const pkgDir = process.cwd();
const srcMappings = join(pkgDir, 'src/mappings');
const distMappings = join(pkgDir, 'dist/mappings');

await mkdir(distMappings, { recursive: true });
const files = await readdir(srcMappings);
for (const f of files) {
  if (!f.endsWith('.json')) continue;
  const name = f.slice(0, -'.json'.length);
  const json = await readFile(join(srcMappings, f), 'utf8');

  // 1. Raw JSON (consumed by dist/index.js's `import ... with { type: "json" }`).
  await copyFile(join(srcMappings, f), join(distMappings, f));

  // 2. ESM module for the `./mappings/<name>` subpath export. JSON is itself a
  //    valid JS expression, so inline it directly as the default export — this
  //    has no runtime dependency on JSON import attributes or the sibling
  //    .json file, so it resolves on every Node ESM version.
  await writeFile(
    join(distMappings, `${name}.js`),
    `// GENERATED by scripts/copy-mappings.mjs — do not edit.\nexport default ${json.trimEnd()};\n`,
  );

  // 3. Type declaration. A ShieldFont mapping is a flat word→word record.
  await writeFile(
    join(distMappings, `${name}.d.ts`),
    `// GENERATED by scripts/copy-mappings.mjs — do not edit.\ndeclare const mapping: Record<string, string>;\nexport default mapping;\n`,
  );

  console.log(`emitted ${name}.json + ${name}.js + ${name}.d.ts → dist/mappings/`);
}
